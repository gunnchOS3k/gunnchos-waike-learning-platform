/* Run against a separately started HTTPS ASGI release candidate; never seeds users. */
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const crypto = require('node:crypto');
const {chromium} = require(require.resolve('@playwright/test', {paths: [process.env.WAIKE_BROWSER_DEPENDENCY_ROOT || process.cwd()]}));
const {default:AxeBuilder} = require(require.resolve('@axe-core/playwright', {paths: [process.env.WAIKE_BROWSER_DEPENDENCY_ROOT || process.cwd()]}));
const base = process.env.WAIKE_STAGING_URL;
if (!base || new URL(base).hostname !== 'localhost') throw new Error('This local acceptance script requires the dedicated localhost staging service');
const out = process.env.WAIKE_BROWSER_EVIDENCE || path.resolve('artifacts/full-delivery/production/browser');
fs.mkdirSync(out, {recursive:true});
(async () => {
  const browser=await chromium.launch({headless:true});
  const context=await browser.newContext({ignoreHTTPSErrors:true,viewport:{width:1280,height:900}});
  const page=await context.newPage();
  const scripts=[]; const errors=[];
  page.on('request',request=>{if(request.resourceType()==='script')scripts.push(new URL(request.url()).pathname);});
  page.on('pageerror',error=>errors.push(error.message));
  const cdp=await context.newCDPSession(page);
  await cdp.send('Network.enable');
  await cdp.send('Network.emulateNetworkConditions',{offline:false,latency:80,downloadThroughput:200*1024/8,uploadThroughput:100*1024/8});
  const start=Date.now();
  await page.goto(`${base}/#/learn/DIGITAL_CONFIDENCE/1`,{waitUntil:'domcontentloaded'});
  await page.getByTestId('full-lesson-content').waitFor({timeout:60000});
  const slowLoadMs=Date.now()-start;
  const courseScripts=scripts.filter(s=>!s.split('/').pop().startsWith('index-') && /assets\/[A-Z_]+-/.test(s));
  if(courseScripts.length!==1 || !courseScripts[0].includes('DIGITAL_CONFIDENCE-'))throw new Error(`Unexpected eager course loads: ${JSON.stringify(courseScripts)}`);
  await cdp.send('Network.emulateNetworkConditions',{offline:false,latency:0,downloadThroughput:-1,uploadThroughput:-1});
  if(await page.getByTestId('login-form').count())throw new Error('Anonymous reading incorrectly requires a login');
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:path.join(out,'dc-desktop.png')});
  const caseResponse=page.waitForResponse(r=>r.url().includes('/api/v1/digital-confidence/cases/1'));
  await page.getByRole('button',{name:'Request fresh practice case',exact:true}).focus();
  await page.keyboard.press('Enter');
  const issued=await caseResponse;
  if(issued.status()!==200)throw new Error('Case service missing on reader origin');
  const parameters=(await issued.json()).parameters;
  const practical=page.getByTestId('dc-practical-1');
  await practical.getByRole('button',{name:'Check practical evidence',exact:true}).click();
  await practical.getByText(/Evidence needs revision/).waitFor();
  const downloadPending=page.waitForEvent('download');
  await practical.getByRole('button',{name:'Download fictional original note'}).click();
  const original=await downloadPending;
  const temp=fs.mkdtempSync(path.join(os.tmpdir(),'waike-local-browser-'));
  const downloaded=path.join(temp,'original-note.txt');
  await original.saveAs(downloaded);
  if(fs.readFileSync(downloaded,'utf8')!==parameters.text)throw new Error('Downloaded fictional note bytes differ from issued case');
  const working=path.join(temp,parameters.filename);
  fs.copyFileSync(downloaded,working);
  // This automates file bytes for engineering acceptance. It does not observe human independence.
  await practical.locator('input[type=file]').setInputFiles(working);
  await practical.getByRole('button',{name:'Check practical evidence',exact:true}).click();
  await practical.getByText(/Evidence checks passed. Human review remains pending/).waitFor();
  await practical.getByText(/Evidence checks passed. Human review remains pending/).scrollIntoViewIfNeeded();
  await page.screenshot({path:path.join(out,'dc-practical-feedback.png')});
  const evidencePending=page.waitForEvent('download');
  await practical.getByRole('button',{name:'Download practical evidence'}).click();
  const evidence=await evidencePending;
  const evidencePath=path.join(temp,'dc-evidence.json');await evidence.saveAs(evidencePath);
  const artifact=JSON.parse(fs.readFileSync(evidencePath,'utf8'));
  if(artifact.answers.file.name!==parameters.filename || artifact.status!=='unsubmitted evidence; human review pending')throw new Error('Evidence download misstates submission or selected file');
  const evidenceHash=crypto.createHash('sha256').update(fs.readFileSync(evidencePath)).digest('hex');
  for(const fieldset of await page.locator('fieldset').all())await fieldset.locator('input[type=radio]').first().check();
  const quizResponse=page.waitForResponse(r=>r.url().includes('/api/v1/public-practice/DIGITAL_CONFIDENCE/1'));
  await page.getByRole('button',{name:'Check my answers',exact:true}).click();
  if((await quizResponse).status()!==200)throw new Error('Quiz service missing on reader origin');
  await page.getByText(/Practice result:/).waitFor();
  await page.getByText('Course completion: not established.').waitFor();
  const accessibility=await new AxeBuilder({page}).include('.browser-learning').withTags(['wcag2a','wcag2aa','wcag21a','wcag21aa']).analyze();
  if(accessibility.violations.length)throw new Error(`Automated reader accessibility violations: ${JSON.stringify(accessibility.violations.map(v=>({id:v.id,impact:v.impact})))}`);
  await page.getByRole('button',{name:'Sign in to my learning Hub'}).click();
  await page.getByTestId('login-form').waitFor();
  if(await page.getByTestId('login-site-id').inputValue())throw new Error('A synthetic site must not be the production default');
  await page.getByRole('button',{name:'Continue public learning'}).click();
  // New course import fails honestly on interruption, then succeeds on retry.
  await page.route('**/assets/SOFTWARE_BUILDER-*.js',route=>route.abort());
  await page.evaluate(()=>{location.hash='#/learn/SOFTWARE_BUILDER/1';});
  await page.getByText(/The course could not be downloaded/).waitFor();
  await page.unroute('**/assets/SOFTWARE_BUILDER-*.js');
  await page.getByRole('button',{name:'Retry course download'}).click();
  // Retry reloads this document: failed ES-module fetches are otherwise cached by the browser loader.
  await page.getByTestId('full-lesson-content').waitFor({timeout:15000});
  const forbidden=await context.request.get(`${base}/curriculum/instructor/answer_keys.json`);
  if(forbidden.status()!==404)throw new Error('Private source is statically served');
  const privateApi=await context.request.get(`${base}/api/v1/assignments`);
  if(privateApi.status()!==401)throw new Error('Private learner API is anonymous');
  const ready=await (await context.request.get(`${base}/readyz`)).json();
  if(ready.seeded_test_fixtures!==false)throw new Error('Staging must have no fixtures');
  const mobile=await browser.newContext({ignoreHTTPSErrors:true,viewport:{width:393,height:852},isMobile:true,hasTouch:true});
  const phone=await mobile.newPage();
  await phone.goto(`${base}/#/learn/NETWORKING_INFRA/1`);
  await phone.getByTestId('full-lesson-content').waitFor();
  if(await phone.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1))throw new Error('Mobile document overflows');
  await phone.screenshot({path:path.join(out,'network-mobile.png')});
  await phone.getByTestId('full-lesson-content').scrollIntoViewIfNeeded();
  await phone.screenshot({path:path.join(out,'network-mobile-reading.png')});
  if(errors.length)throw new Error(`Browser runtime errors: ${errors.join('; ')}`);
  fs.rmSync(temp,{recursive:true});
  const result={kind:'local_https_asgi_acceptance',synthetic_accounts:false,public_url_verified:false,human_learner_validation:false,ready,slow_network:{download_kbps:200,latency_ms:80,time_to_first_course_ms:slowLoadMs},initial_course_scripts:courseScripts,fictional_practical_evidence_sha256:evidenceHash,automated_accessibility:{scope:'Digital Confidence browser reader',wcag_tags:['wcag2a','wcag2aa','wcag21a','wcag21aa'],violations:accessibility.violations.length,human_acceptance:false},checks:['one selected course chunk','anonymous reader','same-origin fresh case with keyboard activation','missing evidence rejected','source-exact fictional note download and local file upload','practical criterion feedback with human review pending','unsubmitted evidence download','same-origin quiz feedback','completion remains unestablished','automated reader accessibility scan','explicit school login without fixture default','interrupted course loading and retry','private source denied','private API denied','mobile networking lesson without horizontal overflow'],screenshots:['dc-desktop.png','dc-practical-feedback.png','network-mobile.png','network-mobile-reading.png']};
  fs.writeFileSync(path.join(out,'acceptance.json'),JSON.stringify(result,null,2)+'\n');
  console.log(JSON.stringify(result,null,2));
  await browser.close();
})().catch(error=>{console.error(error);process.exit(1);});
